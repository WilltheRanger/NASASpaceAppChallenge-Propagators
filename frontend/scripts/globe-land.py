# Source: Natural Earth 1:110m physical land (public domain), as GeoJSON from github.com/martynafford/natural-earth-geojson
# Usage: python3 scripts/globe-land.py ne_110m_land.json src/r2/globe-land.ts 1.2
# Sample Natural Earth land on an equal-area latitude/longitude grid and thin its coastlines, for the orbit globe.
# Writes a TypeScript module.
import json, math, sys

src, out = sys.argv[1], sys.argv[2]
STEP = float(sys.argv[3]) if len(sys.argv) > 3 else 1.2
polys = []
for f in json.load(open(src))['features']:
    g = f['geometry']
    for p in ([g['coordinates']] if g['type'] == 'Polygon' else g['coordinates']):
        xs = [pt[0] for pt in p[0]]; ys = [pt[1] for pt in p[0]]
        polys.append((min(xs), max(xs), min(ys), max(ys), p))

def inside(lon, lat, ring):
    ins = False
    j = len(ring) - 1
    for i in range(len(ring)):
        xi, yi = ring[i]; xj, yj = ring[j]
        if (yi > lat) != (yj > lat) and lon < (xj - xi) * (lat - yi) / (yj - yi) + xi:
            ins = not ins
        j = i
    return ins

def is_land(lon, lat):
    for x0, x1, y0, y1, p in polys:
        if x0 <= lon <= x1 and y0 <= lat <= y1 and inside(lon, lat, p[0]) and not any(inside(lon, lat, h) for h in p[1:]):
            return True
    return False

rows, count = [], 0
nlat = round(180 / STEP)
for j in range(nlat):
    lat = -90 + (j + 0.5) * 180 / nlat
    n = max(1, round(360 * math.cos(math.radians(lat)) / STEP))
    runs, cur = [], None
    for i in range(n):
        lon = -180 + (i + 0.5) * 360 / n
        if is_land(lon, lat):
            count += 1
            if cur is None: cur = [i, 1]
            else: cur[1] += 1
        elif cur is not None:
            runs.append(cur); cur = None
    if cur is not None: runs.append(cur)
    if runs: rows.append([j, n] + [v for r in runs for v in r])

lines, npts = [], 0
for *_, p in polys:
    for ring in p:
        cur = []
        for lon, lat in ring:
            q = (round(lon * 10), round(lat * 10))
            if not cur or abs(q[0] - cur[-1][0]) + abs(q[1] - cur[-1][1]) >= 9:
                cur.append(q)
        if len(cur) > 2:
            cur.append(cur[0])
            lines.append([v for pt in cur for v in pt]); npts += len(cur)

ts = f'''/**
 * Land for the orbit globe: Natural Earth 1:110m land (public domain), sampled on an equal-area latitude and longitude
 * grid, and its coastlines thinned. Generated by scripts/globe-land.py; do not edit by hand.
 */
/** latitude rows: [row, cells in the row, first cell, run length, first cell, run length, ...]; LAT_ROWS rows pole to pole */
export const LAT_ROWS = {nlat}
export const LAND: number[][] = {json.dumps(rows, separators=(',', ':'))}
/** closed coastlines as flat lon, lat lists in tenths of a degree */
export const COAST: number[][] = {json.dumps(lines, separators=(',', ':'))}
'''
open(out, 'w').write(ts)
print('dots', count, 'rows', len(rows), 'coast lines', len(lines), 'points', npts, 'bytes', len(ts))
